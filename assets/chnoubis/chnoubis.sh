  case "$arg" in
    --small)  size=44 ;;
    --medium) size=60 ;;
    --large)  size=80 ;;
    --mono|--no-color) mono=1 ;;
    -h|--help)
      printf '%s\n' 'Usage: bash chnoubis.sh [--small|--medium|--large] [--mono]'
